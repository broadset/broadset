import { escapeXmlText, XML_DECLARATION } from '../ooxml/xml';

/**
 * Speaker-notes emission. `ppt/notesSlides/notesSlideN.xml` carries a
 * per-slide notes body keyed to its slide. `ppt/notesMasters/notesMaster1.xml`
 * is the one-per-package notes master every notes slide references.
 *
 * Broadset stores notes as a plain string on `Page.notes`. OOXML models
 * them as a full `<p:txBody>` with paragraphs; we emit a single
 * paragraph with one run — enough for PowerPoint / LibreOffice to
 * display the notes correctly. Richer run-level notes styling is a
 * spec gap (tracked in pptx.md).
 */

/** Build a `ppt/notesSlides/notesSlideN.xml` body. */
export function buildNotesSlideXml(notes: string): string {
  const safeNotes = escapeXmlText(notes);

  return `${XML_DECLARATION}<p:notes xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main"><p:cSld><p:spTree><p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr><p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr><p:sp><p:nvSpPr><p:cNvPr id="2" name="Notes Placeholder"/><p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr><p:nvPr><p:ph type="body" idx="1"/></p:nvPr></p:nvSpPr><p:spPr/><p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang="en-US"/><a:t>${safeNotes}</a:t></a:r></a:p></p:txBody></p:sp></p:spTree></p:cSld><p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr></p:notes>`;
}

/** Build the one-per-package `ppt/notesMasters/notesMaster1.xml`. */
export function buildNotesMasterXml(): string {
  return `${XML_DECLARATION}<p:notesMaster xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main"><p:cSld><p:bg><p:bgRef idx="1001"><a:schemeClr val="bg1"/></p:bgRef></p:bg><p:spTree><p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr><p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr></p:spTree></p:cSld><p:clrMap bg1="lt1" tx1="dk1" bg2="lt2" tx2="dk2" accent1="accent1" accent2="accent2" accent3="accent3" accent4="accent4" accent5="accent5" accent6="accent6" hlink="hlink" folHlink="folHlink"/></p:notesMaster>`;
}
